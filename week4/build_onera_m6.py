#!/usr/bin/env python3
"""
ONERA M6 wing - geometry generator for a CFD student test case.

Outputs
  onera_m6_wing.geo  Gmsh script: wing solid + half-domain + named patches + size fields
  onera_m6_wing.stl  watertight multi-solid ASCII STL (upper/lower/tip/root) for snappyHexMesh
  onera_m6_preview.png

Geometry (Schmitt & Charpin, AGARD AR-138, 1979; NASA NPARC archive):
  semi-span b = 1.1963 m, root chord c_r = 0.8059 m, LE sweep 30.0 deg,
  TE sweep 15.8 deg, no twist, no dihedral, symmetric ONERA D section.
  Root streamwise section scaled linearly to the tip (standard CFD practice),
  sharp trailing edge (NPARC foilmod coordinates), flat closed tip.
Axes: x streamwise, y spanwise (root on symmetry plane y = 0), z up.
"""
import math
import os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
B = 1.1963
C_ROOT = 0.8059
LE_SWEEP, TE_SWEEP = math.radians(30.0), math.radians(15.8)
C_TIP = C_ROOT - B * (math.tan(LE_SWEEP) - math.tan(TE_SWEEP))
X_LE_TIP = B * math.tan(LE_SWEEP)

foil = np.loadtxt(os.path.join(HERE, "onera_d_foilmod.dat"))     # upper half, LE -> TE


def loop():
    """Closed section, starting at TE: upper surface TE->LE, lower LE->TE (no repeat of TE)."""
    up = foil[::-1]                       # TE ... LE
    lo = foil[1:-1] * [1, -1]             # just after LE ... just before TE
    return np.vstack([up, lo])            # (N,2) in x/c, z/c


def section(eta):
    """3-D points of the section at y = eta*B."""
    c = C_ROOT + eta * (C_TIP - C_ROOT)
    x0 = eta * X_LE_TIP
    s = loop()
    return np.column_stack([x0 + c * s[:, 0], np.full(len(s), eta * B), c * s[:, 1]])


# ------------------------------------------------------------ planform data
S_HALF = 0.5 * B * (C_ROOT + C_TIP)
lam = C_TIP / C_ROOT
MAC = 2 / 3 * C_ROOT * (1 + lam + lam ** 2) / (1 + lam)
AR = (2 * B) ** 2 / (2 * S_HALF)


# ------------------------------------------------------------ Gmsh .geo
def write_geo(path):
    n = len(foil)                         # 72; LE index = n-1 in loop, TE index 0
    L = []
    w = L.append
    w("// ONERA M6 wing - half-model CFD domain for Gmsh (>= 4.8, OpenCASCADE kernel)")
    w("// Generated by build_onera_m6.py. Open in Gmsh and press Mesh > 3D, or:")
    w("//   gmsh onera_m6_wing.geo -3 -o onera_m6_wing.msh")
    w("// Geometry only (no domain): File > Export > .step after removing the domain block.")
    w("// Axes: x streamwise, y spanwise (y=0 symmetry plane), z up. Units: metres.")
    w(f"// b = {B} m, c_root = {C_ROOT} m, c_tip = {C_TIP:.5f} m, LE sweep 30 deg, TE sweep 15.8 deg")
    w(f"// MAC = {MAC:.5f} m, S_half = {S_HALF:.5f} m^2, AR = {AR:.3f}, taper = {lam:.4f}")
    w("")
    w('SetFactory("OpenCASCADE");')
    w("")
    w("// ---------------- user parameters")
    w(f"cr = {C_ROOT};            // root chord (reference length)")
    w("lc_wing = cr/60;          // surface cell size on the wing")
    w("lc_edge = cr/250;         // cell size at leading and trailing edges")
    w("lc_far  = 1.5;            // far-field cell size")
    w("XUP = 10*cr; XDN = 20*cr; ZEXT = 10*cr; YEXT = 8*cr;   // domain extents")
    w("")
    for k, eta in enumerate((0.0, 1.0)):
        P = section(eta)
        base = 1000 * (k + 1)
        w(f"// ---------------- {'root' if k == 0 else 'tip'} section (y = {eta * B:.4f} m)")
        for i, (x, y, z) in enumerate(P):
            w(f"Point({base + i + 1}) = {{{x:.8f}, {y:.8f}, {z:.8f}}};")
        upper = [base + i + 1 for i in range(n)]                       # TE -> LE
        lower = [base + n] + [base + i + 1 for i in range(n, len(P))] + [base + 1]   # LE -> TE
        w(f"Spline({base + 1}) = {{{', '.join(map(str, upper))}}};   // upper TE->LE")
        w(f"Spline({base + 2}) = {{{', '.join(map(str, lower))}}};   // lower LE->TE")
        w(f"Curve Loop({k + 1}) = {{{base + 1}, {base + 2}}};")
        w("")
    w("// ---------------- wing solid (ruled: straight generators between root and tip)")
    w("Ruled ThruSections(1) = {1, 2};")
    w("")
    w("// ---------------- half-domain box with the wing removed")
    w("Box(2) = {-XUP, 0, -ZEXT, XUP + XDN, YEXT, 2*ZEXT};")
    w("BooleanDifference(3) = { Volume{2}; Delete; }{ Volume{1}; Delete; };")
    w("")
    w("e = 1e-4;")
    w(f"wing()      = Surface In BoundingBox{{-e, -e, -0.1, {X_LE_TIP + C_TIP:.6f}+e, {B}+e, 0.1}};")
    w(f"wingEdges() = Curve In BoundingBox{{-e, -e, -0.1, {X_LE_TIP + C_TIP:.6f}+e, {B}+e, 0.1}};")
    w("symmetry()  = Surface In BoundingBox{-XUP-e, -e, -ZEXT-e, XDN+e, e, ZEXT+e};")
    w("inlet()     = Surface In BoundingBox{-XUP-e, -e, -ZEXT-e, -XUP+e, YEXT+e, ZEXT+e};")
    w("outlet()    = Surface In BoundingBox{XDN-e, -e, -ZEXT-e, XDN+e, YEXT+e, ZEXT+e};")
    w("farTop()    = Surface In BoundingBox{-XUP-e, -e, ZEXT-e, XDN+e, YEXT+e, ZEXT+e};")
    w("farBot()    = Surface In BoundingBox{-XUP-e, -e, -ZEXT-e, XDN+e, YEXT+e, -ZEXT+e};")
    w("farSide()   = Surface In BoundingBox{-XUP-e, YEXT-e, -ZEXT-e, XDN+e, YEXT+e, ZEXT+e};")
    w("")
    w('Physical Surface("wing", 1)     = wing();')
    w('Physical Surface("symmetry", 2) = symmetry();')
    w('Physical Surface("inlet", 3)    = inlet();')
    w('Physical Surface("outlet", 4)   = outlet();')
    w('Physical Surface("farfield", 5) = {farTop(), farBot(), farSide()};')
    w('Physical Volume("fluid", 10)    = {3};')
    w("")
    w("// ---------------- size fields: fine at LE/TE, medium on the wing, coarse far away")
    w("Field[1] = Distance;  Field[1].CurvesList = {wingEdges()};  Field[1].Sampling = 400;")
    w("Field[2] = Threshold; Field[2].InField = 1; Field[2].SizeMin = lc_edge; Field[2].SizeMax = lc_far;")
    w("Field[2].DistMin = 0.005; Field[2].DistMax = 3.0;")
    w("Field[3] = Distance;  Field[3].SurfacesList = {wing()};  Field[3].Sampling = 100;")
    w("Field[4] = Threshold; Field[4].InField = 3; Field[4].SizeMin = lc_wing; Field[4].SizeMax = lc_far;")
    w("Field[4].DistMin = 0.02; Field[4].DistMax = 4.0;")
    w("Field[5] = Min; Field[5].FieldsList = {2, 4};")
    w("Background Field = 5;")
    w("")
    w("Mesh.MeshSizeExtendFromBoundary = 0;")
    w("Mesh.MeshSizeFromPoints = 0;")
    w("Mesh.MeshSizeFromCurvature = 0;")
    w("Mesh.Algorithm = 6;       // Frontal-Delaunay (surfaces)")
    w("Mesh.Algorithm3D = 1;     // Delaunay (volume)")
    w("Mesh.Optimize = 1;")
    w("Mesh.MshFileVersion = 2.2;  // for OpenFOAM gmshToFoam")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


# ------------------------------------------------------------ STL
def write_stl(path, n_span=60):
    etas = 0.5 * (1 - np.cos(np.linspace(0, math.pi, n_span)))          # cluster at root & tip
    secs = [section(e) for e in etas]
    m = len(secs[0])
    nU = len(foil)                                                        # loop idx 0..nU-1 = upper
    groups = {"upper": [], "lower": [], "tip": [], "root": []}
    for s in range(n_span - 1):
        A, Bs = secs[s], secs[s + 1]
        for i in range(m):
            j = (i + 1) % m
            # loop runs TE->upper->LE->lower->TE; quad (A_i, A_j, B_j, B_i)
            t1, t2 = (A[i], Bs[j], A[j]), (A[i], Bs[i], Bs[j])
            g = "upper" if i < nU - 1 else "lower"
            groups[g] += [t1, t2]
    for name, S, flip in (("root", secs[0], False), ("tip", secs[-1], True)):
        c = S.mean(0)
        for i in range(m):
            j = (i + 1) % m
            groups[name].append((c, S[j], S[i]) if flip else (c, S[i], S[j]))
    # orient: make every triangle point away from the enclosed volume (checked below)
    allt = np.array([t for g in groups.values() for t in g])
    vol = np.einsum("ij,ij->i", allt[:, 0], np.cross(allt[:, 1], allt[:, 2])).sum() / 6
    if vol < 0:
        groups = {k: [(a, c, b) for a, b, c in v] for k, v in groups.items()}
    with open(path, "w") as f:
        for name, tris in groups.items():
            f.write(f"solid {name}\n")
            for a, b, c in tris:
                nrm = np.cross(b - a, c - a)
                nrm = nrm / (np.linalg.norm(nrm) or 1)
                f.write(f"  facet normal {nrm[0]:.6e} {nrm[1]:.6e} {nrm[2]:.6e}\n    outer loop\n")
                for p in (a, b, c):
                    f.write(f"      vertex {p[0]:.8e} {p[1]:.8e} {p[2]:.8e}\n")
                f.write("    endloop\n  endfacet\n")
            f.write(f"endsolid {name}\n")
    return groups


if __name__ == "__main__":
    write_geo(os.path.join(HERE, "onera_m6_wing.geo"))
    write_stl(os.path.join(HERE, "onera_m6_wing.stl"))
    print(f"c_tip = {C_TIP:.5f} m  taper = {lam:.4f}  MAC = {MAC:.5f} m  S_half = {S_HALF:.5f} m^2  AR = {AR:.3f}")
